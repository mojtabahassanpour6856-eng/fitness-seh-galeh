const fs = require('node:fs');
const assert = require('node:assert/strict');
const html = fs.readFileSync('index.html', 'utf8');
const migration = fs.readFileSync('supabase/migrations/202610220002_restore_workout_id_defaults.sql', 'utf8');
const integration = fs.readFileSync('tests/workout-batch-insert.integration.sql', 'utf8');
const start = html.lastIndexOf('const chosen=groupMode');
assert.notEqual(start, -1, 'latest workout exercise save handler must exist');
const end = html.indexOf('window.deleteWorkoutExercise', start);
assert.notEqual(end, -1, 'end of save handler must exist');
const handler = html.slice(start, end);
const payload = handler.indexOf('const payloads=chosen.map');
const batchWrite = handler.indexOf("inserted=await sbWrite('/trainee_workout_exercises','POST',payloads)");
assert.ok(payload >= 0 && batchWrite > payload, 'selected exercises must be sent in one batch');
assert.ok(handler.includes('inserted.length!==payloads.length'), 'validate returned row count');
assert.ok(handler.includes('same(row.workout_plan_id,planId)'), 'validate returned plan ownership');
assert.ok(handler.includes('window.__workoutAddBusy=false'), 'release save lock');
assert.ok(handler.includes('training_day|is_completed'), 'retain optional-column compatibility fallback');
assert.ok(migration.includes('pg_get_serial_sequence('), 'locate actual identity sequences');
assert.ok(migration.includes('setval('), 'align identity sequences to existing IDs');
assert.ok(!migration.includes('alter column id set default'), 'never SET DEFAULT on identity columns');
assert.ok(integration.includes('generated by default as identity'), 'integration schema must match production identity columns');
assert.ok(!integration.includes('alter column id set default'), 'integration must not alter identity defaults');
console.log('PASS: batch handler guards and identity-backed ID generation checks.');
