-- Disposable PostgreSQL 17 fixture for receipt-review idempotency.
-- This is NOT a production migration. It creates only synthetic tables/data in CI.
\set ON_ERROR_STOP on
create extension if not exists pgcrypto;

create role anon nologin;
create role authenticated nologin;

create schema auth;
create schema private;

create or replace function auth.uid()
returns uuid
language sql stable
as $$
  select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
$$;

create table public.profiles (
  id uuid primary key,
  role text not null check (role in ('coach','trainee'))
);
create table public.trainees (
  id uuid primary key,
  coach_user_id uuid not null references public.profiles(id)
);
create table public.trainee_memberships (
  id bigint generated by default as identity primary key,
  trainee_id uuid not null references public.trainees(id) on delete cascade,
  status text default 'active',
  payment_status text not null default 'unpaid'
    check (payment_status in ('paid','unpaid','pending'))
);
create table public.trainee_payment_receipts (
  id uuid primary key,
  trainee_id uuid not null references public.trainees(id) on delete cascade,
  membership_id bigint references public.trainee_memberships(id),
  submitted_by uuid not null,
  receipt_path text not null,
  amount numeric,
  payment_date date,
  note text,
  review_status text not null default 'pending'
    check (review_status in ('pending','approved','rejected')),
  reviewed_by uuid,
  reviewed_at timestamptz
);
create table public.trainee_payments (
  id bigint generated by default as identity primary key,
  trainee_id uuid not null references public.trainees(id) on delete cascade,
  membership_id bigint references public.trainee_memberships(id),
  amount numeric,
  payment_date date,
  description text,
  created_at timestamptz default now()
);

create table private.operation_ledger (
  actor_uid uuid not null,
  operation_kind text not null,
  operation_id uuid not null,
  request_hash text not null,
  result jsonb,
  created_at timestamptz not null default now(),
  completed_at timestamptz,
  primary key (actor_uid, operation_kind, operation_id)
);

create or replace function private.is_coach()
returns boolean
language sql stable security definer
set search_path = pg_catalog, public
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'coach'
  )
$$;

create or replace function public.review_receipt_idempotent(
  p_receipt_id uuid,
  p_decision text,
  p_operation_id uuid,
  p_fallback_payment_date date
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, private, pg_temp
as $function$
declare
  v_actor uuid := auth.uid();
  v_hash text;
  v_rows integer;
  v_existing_hash text;
  v_result jsonb;
  v_receipt public.trainee_payment_receipts%rowtype;
  v_membership public.trainee_memberships%rowtype;
begin
  if v_actor is null then
    raise exception 'Authentication required' using errcode='28000';
  end if;
  if not coalesce(private.is_coach(), false) then
    raise exception 'Coach role required' using errcode='42501';
  end if;
  if p_receipt_id is null or p_operation_id is null or p_fallback_payment_date is null or p_decision is null
     or p_decision not in ('approved','rejected') then
    raise exception 'Invalid receipt review request' using errcode='22023';
  end if;

  -- Lock and authorize the receipt before computing the request hash.
  -- membership_id is part of the immutable business identity of this review.
  select * into v_receipt
  from public.trainee_payment_receipts
  where id=p_receipt_id
  for update;

  if not found then
    raise exception 'Receipt not found' using errcode='P0002';
  end if;

  if not exists (
    select 1 from public.trainees t
    where t.id=v_receipt.trainee_id and t.coach_user_id=v_actor
  ) then
    raise exception 'Coach cannot review this trainee receipt'
      using errcode='42501';
  end if;

  v_hash := encode(digest(jsonb_build_object(
    'receipt_id',p_receipt_id,
    'membership_id',v_receipt.membership_id,
    'decision',p_decision,
    'fallback_payment_date',p_fallback_payment_date
  )::text,'sha256'),'hex');

  insert into private.operation_ledger
    (actor_uid,operation_kind,operation_id,request_hash)
  values
    (v_actor,'receipt_review',p_operation_id,v_hash)
  on conflict do nothing;
  get diagnostics v_rows = row_count;

  if v_rows = 0 then
    select request_hash,result
      into v_existing_hash,v_result
    from private.operation_ledger
    where actor_uid=v_actor
      and operation_kind='receipt_review'
      and operation_id=p_operation_id
    for update;

    if v_existing_hash is distinct from v_hash then
      raise exception 'Operation ID was already used with a different payload'
        using errcode='22023';
    end if;
    if v_result is not null then
      return v_result;
    end if;
    raise exception 'Operation is not in a replayable terminal state'
      using errcode='55000';
  end if;

  if v_receipt.review_status <> 'pending' then
    raise exception 'Receipt is already in a terminal state'
      using errcode='55000';
  end if;

  if p_decision='approved' then
    if v_receipt.membership_id is null then
      raise exception 'Receipt is not linked to a specific membership; manual reconciliation required'
        using errcode='23514';
    end if;
    select * into v_membership
      from public.trainee_memberships
     where id=v_receipt.membership_id and trainee_id=v_receipt.trainee_id
     for update;
    if not found then
      raise exception 'Receipt membership does not belong to the receipt trainee'
        using errcode='23514';
    end if;
    insert into public.trainee_payments(trainee_id,membership_id,amount,payment_date,description)
    values(v_receipt.trainee_id,v_receipt.membership_id,v_receipt.amount,
           coalesce(v_receipt.payment_date,p_fallback_payment_date),'تأیید فیش واریزی');
    update public.trainee_memberships
       set status='active',payment_status='paid'
     where id=v_receipt.membership_id and trainee_id=v_receipt.trainee_id;
    update public.trainee_payment_receipts
       set review_status='approved',reviewed_by=v_actor,reviewed_at=now()
     where id=v_receipt.id;
  else
    update public.trainee_payment_receipts
       set review_status='rejected',reviewed_by=v_actor,reviewed_at=now()
     where id=v_receipt.id;
  end if;

  v_result := jsonb_build_object(
    'success',true,
    'receipt_id',v_receipt.id,
    'membership_id',v_receipt.membership_id,
    'decision',p_decision,
    'payment_created',(p_decision='approved')
  );
  update private.operation_ledger
     set result=v_result,completed_at=now()
   where actor_uid=v_actor
     and operation_kind='receipt_review'
     and operation_id=p_operation_id;

  return v_result;
end;
$function$;

