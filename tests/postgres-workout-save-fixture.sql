-- Disposable PostgreSQL test schema only. Never run against production.
\set ON_ERROR_STOP on
drop schema if exists public cascade;
create schema public;
drop schema if exists private cascade;
create schema private;
drop schema if exists auth cascade;
create schema auth;
drop role if exists authenticated;
drop role if exists anon;
create role anon nologin;
create role authenticated nologin;

create table public.trainees (id uuid primary key);
create table public.exercises (id bigint primary key, name text not null);
create table public.trainee_workout_plans (
  id bigint generated by default as identity primary key,
  trainee_id uuid not null references public.trainees(id),
  title text not null, plan_date date, goal text, notes text,
  created_at timestamptz not null default now()
);
create table public.trainee_workout_exercises (
  id bigint generated by default as identity primary key,
  workout_plan_id bigint not null references public.trainee_workout_plans(id),
  exercise_id bigint not null references public.exercises(id),
  sets integer default 0, reps text, rest_seconds integer default 0, notes text,
  sort_order integer default 1, training_system text default 'normal',
  group_key text, training_day text, is_completed boolean default false
);

create function auth.uid() returns uuid language sql stable
as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
create function private.is_coach() returns boolean language sql stable security definer
set search_path = ''
as $$ select coalesce(nullif(current_setting('test.is_coach', true), '')::boolean, false) $$;
create function private.can_access_trainee(p_trainee_id uuid) returns boolean language sql stable security definer
set search_path = ''
as $$
 select coalesce(nullif(current_setting('test.is_coach', true), '')::boolean, false)
    and nullif(current_setting('test.trainee_id', true), '')::uuid = p_trainee_id
$$;

alter table public.trainee_workout_plans enable row level security;
alter table public.trainee_workout_exercises enable row level security;
alter table public.trainees enable row level security;
alter table public.exercises enable row level security;
create policy coach_plan_access on public.trainee_workout_plans for all to authenticated
 using (private.can_access_trainee(trainee_id)) with check (private.can_access_trainee(trainee_id));
create policy coach_exercise_access on public.trainee_workout_exercises for all to authenticated
 using (exists (select 1 from public.trainee_workout_plans p where p.id = workout_plan_id and private.can_access_trainee(p.trainee_id)))
 with check (exists (select 1 from public.trainee_workout_plans p where p.id = workout_plan_id and private.can_access_trainee(p.trainee_id)));
create policy coach_trainee_read on public.trainees for select to authenticated using (private.can_access_trainee(id));
create policy exercise_bank_read on public.exercises for select to authenticated using (true);

grant usage on schema public, private, auth to authenticated;
grant execute on function auth.uid() to authenticated;
grant execute on function private.is_coach() to authenticated;
grant execute on function private.can_access_trainee(uuid) to authenticated;
grant select on public.trainees, public.exercises to authenticated;
grant select, insert, update, delete on public.trainee_workout_plans, public.trainee_workout_exercises to authenticated;
grant usage, select on all sequences in schema public to authenticated;

