import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const html=fs.readFileSync('index.html','utf8');
const match=html.match(/<script id="seh-coach-first-load-guard">([\s\S]*?)<\/script>/);
assert.ok(match,'coach first-load guard must exist');
let calls=0,shouldFail=true,release;
const window={loadClients:async()=>{calls++;if(shouldFail)throw new Error('temporary network failure');return ['trainee'];}};
const document={readyState:'loading',addEventListener(){} ,getElementById(){return null;}};
vm.runInNewContext(match[1],{window,document,Promise,console,setInterval,clearInterval});
assert.equal(window.__sehCoachListLoadAttempted,undefined);
await assert.rejects(window.loadClients(),/temporary network failure/);
assert.notEqual(window.__sehCoachListLoadAttempted,true,'failed load must not be marked as completed');
shouldFail=false;
const result=await window.loadClients();
assert.deepEqual(Array.from(result),['trainee']);
assert.equal(window.__sehCoachListLoadAttempted,true,'successful load marks the list ready');
assert.equal(calls,2,'a failed initial load can be retried successfully');
console.log('PASS: transient coach-list load failure does not poison the completion flag; a later retry succeeds.');
