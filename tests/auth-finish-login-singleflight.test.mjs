import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const html=fs.readFileSync('index.html','utf8');
const match=html.match(/<script id="seh-auth-finish-login-singleflight-v1">([\s\S]*?)<\/script>/);
assert.ok(match,'single-flight login guard must be present in the real app HTML');
let calls=0,release;
const gate=new Promise(resolve=>{release=resolve;});
const window={finishLogin:async function(user){calls++;await gate;return user.id;}};
vm.runInNewContext(match[1],{window,Promise,String});
assert.equal(window.__sehFinishLoginGuardInstalled,true);
const user={id:'same-user'};
const first=window.finishLogin(user),second=window.finishLogin(user);
assert.equal(first,second,'parallel calls for the same user must share one promise');
await Promise.resolve();
assert.equal(calls,1,'underlying login pipeline must run once');
let differentUserRejected=false;
try{await window.finishLogin({id:'different-user'});}catch(e){differentUserRejected=/در حال انجام/.test(e.message);}
assert.equal(differentUserRejected,true,'different accounts must not race');
release();
assert.equal(await first,'same-user');
assert.equal(await window.finishLogin(user),'same-user');
assert.equal(calls,2,'guard must release after completion');
let failCalls=0;
const failingWindow={finishLogin:async()=>{failCalls++;throw new Error('expected failure');}};
vm.runInNewContext(match[1],{window:failingWindow,Promise,String});
await assert.rejects(failingWindow.finishLogin({id:'failure-user'}),/expected failure/);
await assert.rejects(failingWindow.finishLogin({id:'failure-user'}),/expected failure/);
assert.equal(failCalls,2,'failed attempts must release the guard for retry');
console.log('PASS: concurrent finishLogin calls are deduplicated; account races blocked; guard releases after success/failure.');
