\set ON_ERROR_STOP on
CREATE ROLE anon NOLOGIN;
CREATE ROLE authenticated NOLOGIN;
CREATE SCHEMA auth;
CREATE SCHEMA private;
GRANT USAGE ON SCHEMA public, auth, private TO authenticated;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
  SELECT nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
$$;
CREATE FUNCTION private.is_coach() RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT coalesce(current_setting('test.is_coach', true), 'false') = 'true'
$$;
CREATE FUNCTION private.can_access_trainee(p_trainee_id uuid) RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT p_trainee_id::text = coalesce(current_setting('test.allowed_trainee', true), '')
$$;
CREATE TABLE public.trainees (id uuid PRIMARY KEY);
CREATE TABLE public.exercises (id bigint PRIMARY KEY, name text NOT NULL);
CREATE TABLE public.trainee_workout_plans (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trainee_id uuid NOT NULL REFERENCES public.trainees(id),
  title text NOT NULL,
  goal text,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  plan_date date
);
CREATE TABLE public.trainee_workout_exercises (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workout_plan_id bigint NOT NULL REFERENCES public.trainee_workout_plans(id) ON DELETE CASCADE,
  exercise_id bigint NOT NULL REFERENCES public.exercises(id),
  sets integer NOT NULL,
  reps text,
  rest_seconds integer NOT NULL,
  notes text,
  sort_order integer NOT NULL,
  training_system text,
  group_key text,
  created_at timestamptz NOT NULL DEFAULT now(),
  training_day text,
  is_completed boolean
);
ALTER TABLE public.trainees ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.exercises ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.trainee_workout_plans ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.trainee_workout_exercises ENABLE ROW LEVEL SECURITY;
CREATE POLICY trainee_select ON public.trainees FOR SELECT TO authenticated USING (private.is_coach() AND private.can_access_trainee(id));
CREATE POLICY exercise_bank_select ON public.exercises FOR SELECT TO authenticated USING (true);
CREATE POLICY plan_select ON public.trainee_workout_plans FOR SELECT TO authenticated USING (private.is_coach() AND private.can_access_trainee(trainee_id));
CREATE POLICY plan_insert ON public.trainee_workout_plans FOR INSERT TO authenticated WITH CHECK (private.is_coach() AND private.can_access_trainee(trainee_id));
CREATE POLICY plan_update ON public.trainee_workout_plans FOR UPDATE TO authenticated USING (private.is_coach() AND private.can_access_trainee(trainee_id)) WITH CHECK (private.is_coach() AND private.can_access_trainee(trainee_id));
CREATE POLICY exercise_select ON public.trainee_workout_exercises FOR SELECT TO authenticated USING (
  EXISTS (SELECT 1 FROM public.trainee_workout_plans p WHERE p.id = workout_plan_id AND private.is_coach() AND private.can_access_trainee(p.trainee_id))
);
CREATE POLICY exercise_insert ON public.trainee_workout_exercises FOR INSERT TO authenticated WITH CHECK (
  EXISTS (SELECT 1 FROM public.trainee_workout_plans p WHERE p.id = workout_plan_id AND private.is_coach() AND private.can_access_trainee(p.trainee_id))
);
CREATE POLICY exercise_delete ON public.trainee_workout_exercises FOR DELETE TO authenticated USING (
  EXISTS (SELECT 1 FROM public.trainee_workout_plans p WHERE p.id = workout_plan_id AND private.is_coach() AND private.can_access_trainee(p.trainee_id))
);
