-- DRAFT ONLY — DO NOT APPLY TO PRODUCTION.
-- Audited manual mapping for legacy receipts whose membership_id is NULL.
-- Depends on PR #226's composite keys and receipt/payment membership columns.

begin;

create schema if not exists private;

create table if not exists private.receipt_reconciliation_operations (
  actor_uid uuid not null,
  operation_id uuid not null,
  request_payload jsonb not null,
  result jsonb,
  created_at timestamptz not null default now(),
  completed_at timestamptz,
  primary key (actor_uid, operation_id)
);

create table if not exists private.receipt_membership_reconciliation_audit (
  id bigint generated by default as identity primary key,
  receipt_id uuid not null unique,
  trainee_id uuid not null,
  membership_id bigint not null,
  coach_user_id uuid not null,
  reason text not null check (char_length(btrim(reason)) between 8 and 1000),
  confirmed_not_already_recorded boolean not null check (confirmed_not_already_recorded),
  operation_id uuid not null unique,
  created_at timestamptz not null default now(),
  constraint receipt_reconciliation_audit_receipt_fk
    foreign key (trainee_id, receipt_id)
    references public.trainee_payment_receipts (trainee_id, id)
    on delete cascade,
  constraint receipt_reconciliation_audit_membership_fk
    foreign key (trainee_id, membership_id)
    references public.trainee_memberships (trainee_id, id)
    on delete no action
);

revoke all on table private.receipt_reconciliation_operations
  from public, anon, authenticated;
revoke all on table private.receipt_membership_reconciliation_audit
  from public, anon, authenticated;

create or replace function public.reconcile_legacy_trainee_receipt_membership(
  p_receipt_id uuid,
  p_membership_id bigint,
  p_operation_id uuid,
  p_reason text,
  p_confirm_not_already_recorded boolean
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_actor uuid := auth.uid();
  v_receipt public.trainee_payment_receipts%rowtype;
  v_payload jsonb;
  v_existing_payload jsonb;
  v_result jsonb;
  v_rows integer;
begin
  if v_actor is null then
    raise exception 'Authentication required' using errcode = '28000';
  end if;

  if p_receipt_id is null or p_membership_id is null
     or p_operation_id is null
     or p_reason is null
     or char_length(btrim(p_reason)) < 8
     or char_length(btrim(p_reason)) > 1000
     or p_confirm_not_already_recorded is distinct from true then
    raise exception 'Manual reconciliation requires a membership, reason, and explicit payment-history confirmation'
      using errcode = '22023';
  end if;

  if not exists (
    select 1 from public.profiles p
     where p.id = v_actor and p.role = 'coach'
  ) then
    raise exception 'Coach role required' using errcode = '42501';
  end if;

  select * into v_receipt
    from public.trainee_payment_receipts
   where id = p_receipt_id
   for update;

  if not found then
    raise exception 'Receipt not found' using errcode = 'P0002';
  end if;

  if not exists (
    select 1 from public.trainees t
     where t.id = v_receipt.trainee_id
       and t.coach_user_id = v_actor
  ) then
    raise exception 'Coach cannot reconcile this trainee receipt'
      using errcode = '42501';
  end if;

  v_payload := jsonb_build_object(
    'receipt_id', p_receipt_id,
    'membership_id', p_membership_id,
    'reason', btrim(p_reason),
    'confirmed_not_already_recorded', p_confirm_not_already_recorded
  );

  insert into private.receipt_reconciliation_operations
    (actor_uid, operation_id, request_payload)
  values
    (v_actor, p_operation_id, v_payload)
  on conflict do nothing;

  get diagnostics v_rows = row_count;

  if v_rows = 0 then
    select request_payload, result
      into v_existing_payload, v_result
      from private.receipt_reconciliation_operations
     where actor_uid = v_actor
       and operation_id = p_operation_id
     for update;

    if v_existing_payload is distinct from v_payload then
      raise exception 'Operation ID was already used with a different reconciliation'
        using errcode = '22023';
    end if;

    if v_result is not null then
      return v_result;
    end if;

    raise exception 'Reconciliation operation is not in a replayable terminal state'
      using errcode = '55000';
  end if;

  if v_receipt.review_status is distinct from 'pending' then
    raise exception 'Only pending legacy receipts can be reconciled'
      using errcode = '55000';
  end if;

  if v_receipt.membership_id is not null then
    raise exception 'Receipt already has a membership link'
      using errcode = '23505';
  end if;

  if exists (
    select 1 from public.trainee_payments p
     where p.receipt_id = v_receipt.id
  ) then
    raise exception 'Receipt already has a linked payment; manual accounting review required'
      using errcode = '23505';
  end if;

  perform 1
    from public.trainee_memberships m
   where m.id = p_membership_id
     and m.trainee_id = v_receipt.trainee_id
   for update;

  if not found then
    raise exception 'Selected membership does not belong to this trainee'
      using errcode = '23514';
  end if;

  insert into private.receipt_membership_reconciliation_audit
    (receipt_id, trainee_id, membership_id, coach_user_id, reason,
     confirmed_not_already_recorded, operation_id)
  values
    (v_receipt.id, v_receipt.trainee_id, p_membership_id, v_actor,
     btrim(p_reason), true, p_operation_id);

  update public.trainee_payment_receipts
     set membership_id = p_membership_id
   where id = v_receipt.id
     and trainee_id = v_receipt.trainee_id
     and membership_id is null
     and review_status = 'pending';

  get diagnostics v_rows = row_count;
  if v_rows <> 1 then
    raise exception 'Receipt changed during reconciliation; no mapping was committed'
      using errcode = '40001';
  end if;

  v_result := jsonb_build_object(
    'success', true,
    'receipt_id', v_receipt.id,
    'trainee_id', v_receipt.trainee_id,
    'membership_id', p_membership_id,
    'operation_id', p_operation_id,
    'review_status', 'pending',
    'payment_created', false
  );

  update private.receipt_reconciliation_operations
     set result = v_result,
         completed_at = now()
   where actor_uid = v_actor
     and operation_id = p_operation_id;

  return v_result;
end;
$function$;

revoke all on function public.reconcile_legacy_trainee_receipt_membership(
  uuid, bigint, uuid, text, boolean
) from public, anon;

grant execute on function public.reconcile_legacy_trainee_receipt_membership(
  uuid, bigint, uuid, text, boolean
) to authenticated;

commit;
